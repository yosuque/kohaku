def test_canonical_stringify_and_sha256(cross_language_fixture: dict[str, Any]) -> None:
    for case in cross_language_fixture["canonical"]:
        got = canonical_stringify(case["value"])
        assert got == case["canonical"], f"canonical mismatch for {case['value']!r}"
        assert sha256_hex(got) == case["sha256"]


def test_intent_hash(cross_language_fixture: dict[str, Any]) -> None:
    for case in cross_language_fixture["intents"]:
        got = compute_intent_hash(IntentInput(canonical=case["canonical"], params=case["params"]))
        assert got == case["hash"], f"intent hash mismatch for {case['canonical']}"


def test_spec_and_structure_hash(cross_language_fixture: dict[str, Any]) -> None:
    spec_case = cross_language_fixture["spec"]
    spec = parse_spec(json.loads((REPO_ROOT / spec_case["file"]).read_text(encoding="utf-8")))
    assert compute_spec_hash(spec) == spec_case["specHash"]
    assert compute_structure_hash(spec) == spec_case["structureHash"]


