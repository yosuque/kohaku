# --- Compliance Evidence Pack (design.md #67) ---
#
# Lives in its own directory (spec/test/fixtures/evidence-pack/: a store + a manifest + a detached
# signature), not inside cross-language-canonical.json above -- see generate-cross-language-fixtures.ts's
# own comment on why. The TS counterpart is spec/test/cross-language.test.ts's matching describe block.

_ED25519_PKCS8_PREFIX = bytes.fromhex("302e020100300506032b657004220420")
# Same RFC 8032 §7.1 TEST 1 vector packages/lineage/test/evidence-sign.test.ts and
# python/kohaku/tests/lineage/test_evidence.py independently pin (a well-known, publicly verifiable
# vector, not a fixture-specific secret).
_RFC8032_TEST1_SECRET_KEY_SEED = bytes.fromhex(
    "9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60"
)
_RFC8032_TEST1_PUBLIC_KEY = bytes.fromhex(
    "d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a"
)


def _load_evidence_pack_fixture() -> dict[str, Any]:
    directory = REPO_ROOT / "spec/test/fixtures/evidence-pack"
    return {
        "store": json.loads((directory / "store.json").read_text(encoding="utf-8")),
        "manifest": json.loads((directory / "manifest.json").read_text(encoding="utf-8")),
        "signature": (directory / "manifest.sig").read_text(encoding="utf-8").strip(),
    }


class _StoreEvidenceSource:
    """Reconstructs an EvidenceSource from the fixture's store.json (mirrors the TS golden test's
    `evidenceSourceFromStore`)."""

    def __init__(self, store: dict[str, Any]) -> None:
        self._events = [
            LineageEventRecord(
                id=e["id"],
                ts=e["ts"],
                actor=LineageActor(**e["actor"]),
                type=e["type"],
                payload=e.get("payload", {}),
                tenant=e.get("tenant"),
            )
            for e in store["events"]
        ]
        self._promotions: list[PromotionState] = []
        for raw in store["promotions"]:
            state = validate_promotion_state(raw)
            assert state is not None
            self._promotions.append(state)
        self._fixations: list[FixationRecord] = []
        for raw in store["fixations"]:
            record = validate_fixation_record(raw)
            assert record is not None
            self._fixations.append(record)

    async def list_lineage(self, filter: LineageFilter | None = None) -> list[LineageEventRecord]:
        f = filter or LineageFilter()

        def matches(e: LineageEventRecord) -> bool:
            if f.tenant is not None and e.tenant != f.tenant:
                return False
            if f.since is not None and e.ts < f.since:
                return False
            if f.until is not None and e.ts > f.until:
                return False
            return True

        return [e for e in self._events if matches(e)]

    async def page_lineage(self, req: LineagePageRequest) -> LineagePage:
        return page_lineage_events(self._events, req)

    async def list_promotion_states(self, tenant: str | None = None) -> list[PromotionState]:
        return (
            self._promotions
            if tenant is None
            else [p for p in self._promotions if p.tenant == tenant]
        )

    async def list_fixations(self, tenant: str | None = None) -> list[FixationRecord]:
        return (
            self._fixations
            if tenant is None
            else [f for f in self._fixations if f.tenant == tenant]
        )


def test_evidence_pack_manifest() -> None:
    """build_evidence_pack must reproduce the TS-generated fixture manifest byte-for-byte."""
    fixture = _load_evidence_pack_fixture()
    store = fixture["store"]
    manifest_fixture = EvidenceManifest.model_validate(fixture["manifest"])

    async def run() -> EvidenceManifest:
        pack = await build_evidence_pack(
            source=_StoreEvidenceSource(store),
            scope=EvidencePackScope(
                since=store["scope"]["since"],
                until=store["scope"]["until"],
                tenant=store["scope"].get("tenant"),
            ),
            generator=store["generator"],
            signer=manifest_fixture.signer,
            now=lambda: str(store["generatedAt"]),
        )
        return pack.manifest

    manifest = asyncio.run(run())
    assert manifest.canonical_dict() == manifest_fixture.canonical_dict()
    assert canonical_stringify(manifest.canonical_dict()) == canonical_stringify(
        manifest_fixture.canonical_dict()
    )


def test_evidence_pack_signature() -> None:
    """sign_manifest must reproduce the fixture's signature bytes exactly (Ed25519 is deterministic)."""
    pytest.importorskip("cryptography", reason="the `evidence` optional extra is not installed")
    fixture = _load_evidence_pack_fixture()
    manifest_fixture = EvidenceManifest.model_validate(fixture["manifest"])
    private_key = import_ed25519_private_key_pkcs8(
        _ED25519_PKCS8_PREFIX + _RFC8032_TEST1_SECRET_KEY_SEED
    )
    signature = sign_manifest(manifest_fixture, private_key)
    assert signature == fixture["signature"]


def test_evidence_pack_signature_verifies_against_rfc8032_public_key() -> None:
    pytest.importorskip("cryptography", reason="the `evidence` optional extra is not installed")
    fixture = _load_evidence_pack_fixture()
    manifest_fixture = EvidenceManifest.model_validate(fixture["manifest"])
    public_key = import_ed25519_public_key_raw(_RFC8032_TEST1_PUBLIC_KEY)
    assert verify_manifest_signature(manifest_fixture, fixture["signature"], public_key) is True
