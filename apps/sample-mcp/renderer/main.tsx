/**
 * Shared renderer that runs inside the MCP Apps iframe (Strategy A: the same rendering code as the Web app). It has 2 modes:
 * - Normal mode (ext-apps bridge): receive {spec, capability} via ui/notifications/tool-result →
 *   render with renderer-react. Data resolution goes through the app-only tool kohaku_resolve_binding (bulk data
 *   does not pass through the model's context). Component events go kohaku_event → re-render with the new Spec.
 *   Writes (presentForm submit / action.button) go through the app-only tool kohaku_action.
 * - Snapshot mode (#kohaku-snapshot is non-null): self-contained HTML generated by kohaku_render_snapshot
 *   for UI-incapable hosts (CLI, etc.). It does not connect to the bridge; it renders statically from the
 *   embedded Spec + resolved data (re-composition events are no-op). The goal is to display it with the same rendering code as the Web app.
 *
 * Hang countermeasures: because Claude Desktop's App Bridge has a known
 * issue where it does not respond to widget-originated tools/call (ext-apps issue #386), (A) initial data is
 * co-embedded in the tool-result's _meta so the initial display appears even if the host's tool call is broken,
 * and (B) callServerTool has a timeout and a diagnostic display to avoid an indefinite "loading". Furthermore,
 * (C) the receiving side is logged unconditionally so we can distinguish "the host is not sending" from "it is
 * sending but the shape is different" on real devices, and (D) when the tool-result does not arrive, a self-recovery
 * that re-calls a model-visible tool from the widget is attempted once. Connection / reception milestones are printed
 * with console.log("[kohaku] …"), traceable in Claude Desktop's Developer Mode (Cmd+Option+I).
 */

