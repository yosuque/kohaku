/**
 * The projection of the pnpm catalog that `kohaku init` pins in a generated project, and the renderer for the
 * file that holds it (`cli/src/init/versions.ts`).
 *
 * The package list lives here, not in `scripts/sync-init-versions.ts`, so the `kohaku init` render test can
 * import it without running the generator.
 */

/**
 * Packages the generated project depends on directly, in the order they appear in `versions.ts`. Add a name
 * here, run `pnpm init:versions`, and the table follows the catalog from then on.
 */
export const INIT_EXTERNAL_PACKAGES = [
  "hono",
  "@hono/node-server",
  "zod",
  "react",
  "react-dom",
  "@types/react",
  "@types/react-dom",
  "@types/node",
  "vite",
  "@vitejs/plugin-react",
  "tsx",
  "typescript",
  "vitest",
  "@ai-sdk/anthropic",
  "@ai-sdk/openai-compatible",
  "@modelcontextprotocol/server",
  "@modelcontextprotocol/node",
];

/**
 * Renders `cli/src/init/versions.ts`. The output is already in Biome's format (bare keys where a key is a
 * valid identifier, quoted otherwise) so `pnpm check:ci` accepts the generated file as is.
 *
 * @param {Map<string, string>} catalog From `readCatalog`.
 * @returns {string} The file contents.
 * @throws {Error} When a package in `INIT_EXTERNAL_PACKAGES` is missing from the catalog.
 */
export function renderInitVersions(catalog) {
  const missing = INIT_EXTERNAL_PACKAGES.filter((name) => !catalog.has(name));
  if (missing.length > 0) {
    throw new Error(`not in the pnpm catalog: ${missing.join(", ")}`);
  }
  const lines = INIT_EXTERNAL_PACKAGES.map((name) => {
    const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
    return `  ${key}: ${JSON.stringify(catalog.get(name))},`;
  });
  return [
    "// GENERATED by scripts/sync-init-versions.ts — do not edit. Run `pnpm init:versions` after a catalog change.",
    "/**",
    " * Versions the generated project depends on: the projection of pnpm-workspace.yaml's catalog that",
    " * scripts/lib/init-versions.mjs lists, so a quickstart project runs on exactly what this repository tests",
    " * against (CI fails on drift, and a render test asserts the match in both directions).",
    " */",
    "export const EXTERNAL_VERSIONS = {",
    ...lines,
    "} as const satisfies Record<string, string>;",
    "",
  ].join("\n");
}
