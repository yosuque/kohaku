/** The files `initProject` writes for one mode, in its order: the rendered project, then `.env`, then (MCP only) the Claude Desktop config. */
async function generated(mcp: boolean): Promise<ProjectFile[]> {
  const dataset = await readDataFile(FIXTURE);
  const profile = inferProfile("sales", dataset);
  const rows = normalizeRows(dataset, profile);
  const files = renderProjectFiles(profile, rows, { name: NAME, mcp });
  const extras: ProjectFile[] = [{ path: ".env", content: renderEnvFile(SECRET) }];
  if (mcp) {
    extras.push({
      path: "claude_desktop_config.example.json",
      content: renderClaudeDesktopConfigExample({ name: NAME, outDir: OUT_DIR, execPath: EXEC_PATH }),
    });
  }
  return [...files, ...extras];
}

function goldenFilesOnDisk(dir: string): string[] {
  return (readdirSync(dir, { recursive: true }) as string[])
    .filter((entry) => statSync(join(dir, entry)).isFile())
    .map((entry) => entry.split("\\").join("/"))
    .sort();
}

describe.each([
  { mode: "plain", mcp: false, expectedFiles: PLAIN_FILES },
  { mode: "mcp", mcp: true, expectedFiles: MCP_FILES },
])("generated project golden ($mode)", ({ mode, mcp, expectedFiles }) => {
  const goldenDir = join(GOLDEN_ROOT, mode);

  it("generates exactly the pinned file list, in order", async () => {
    const files = await generated(mcp);
    expect(files.map((f) => f.path)).toEqual(expectedFiles);
  });

  it("matches every golden file byte for byte, with no stale golden left over", async () => {
    const files = await generated(mcp);
    if (UPDATE) {
      for (const f of files) {
        const target = join(goldenDir, `${f.path}.golden`);
        mkdirSync(dirname(target), { recursive: true });
        writeFileSync(target, normalize(f.content));
      }
    }
    for (const f of files) {
      expect(readFileSync(join(goldenDir, `${f.path}.golden`), "utf8"), f.path).toBe(normalize(f.content));
    }
    expect(goldenFilesOnDisk(goldenDir)).toEqual(files.map((f) => `${f.path}.golden`).sort());
  });
});
